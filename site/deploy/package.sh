#!/bin/sh
# Turn a built site into the tree that is published on the site-dist branch:
#
#     site/        the built site
#     VERSION      the commit the site was built from
#     SHA256SUMS   a checksum for every file under site/
#
#     sh site/deploy/package.sh site/dist OUTPUT_DIRECTORY COMMIT
set -eu
LC_ALL=C
export LC_ALL

[ $# -eq 3 ] || { echo "usage: package.sh DIST OUTPUT_DIRECTORY COMMIT" >&2; exit 2; }
dist=$1
out=$2
version=$3

[ -f "$dist/index.html" ] || { echo "package.sh: $dist holds no index.html" >&2; exit 1; }
mkdir -p "$out"
[ -z "$(ls -A "$out")" ] || { echo "package.sh: $out is not empty" >&2; exit 1; }

cp -R "$dist" "$out/site"
printf '%s\n' "$version" > "$out/VERSION"
(
  cd "$out/site"
  find . -type f | sort | while IFS= read -r path; do sha256sum "$path"; done
) > "$out/SHA256SUMS"

cat > "$out/README.md" <<'README'
# Built site

This branch is generated by the "Deploy site" workflow and is overwritten on
every build; do not edit it. It holds the built Foretaster site so that a web
host with no inbound access can download it. See `site/README.md` on the
`main` branch.
README
