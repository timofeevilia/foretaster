def render_html(report: Report) -> str:
    summary = report.summary
    tiles = "".join(
        f'<div class="tile" style="--c: var(--{severity.value})">'
        f"<b>{count}</b><span>{severity.value}</span></div>"
        for severity, count in summary.findings.items()
    )
    notices = "".join(
        f'<div class="notice"><b>Scan incomplete:</b> {escape(error.kind)} '
        f"{escape(error.subject)}: {escape(error.message)}</div>"
        for error in report.errors
    )
    if not report.findings and not report.errors:
        notices = '<div class="notice ok">No findings.</div>'
    findings = "".join(_finding(finding) for finding in report.findings)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'">
<meta name="referrer" content="no-referrer">
<title>Foretaster report</title>
<style>{_CSS}</style>
</head>
<body>
<main>
<h1>Foretaster report</h1>
<p class="sub">{summary.configs} configuration file(s), {summary.servers} server(s),
{summary.tools} tool(s) scanned.</p>
<div class="tiles">{tiles}</div>
{notices}
{findings}
<footer>Generated by Foretaster {escape(report.tool.version)}.</footer>
</main>
</body>
</html>
"""


def _finding(finding: Finding) -> str:
    where = escape(str(finding.location.path))
    if finding.location.line:
        where += f":{finding.location.line}"
    if finding.server:
        where += f" &middot; server <b>{escape(finding.server)}</b>"
    if finding.tool:
        where += f" &middot; tool <b>{escape(finding.tool)}</b>"
    evidence = f"<pre>{escape(finding.evidence)}</pre>" if finding.evidence else ""
    references = (
        f'<p class="refs">{escape(" · ".join(finding.references))}</p>'
        if finding.references
        else ""
    )
    return (
        f'<article class="finding" style="--c: var(--{_css_name(finding.severity)})">'
        f'<h2><span class="badge">{finding.severity.value}</span>'
        f'<span class="id">{escape(finding.rule_id)}</span>{escape(finding.title)}</h2>'
        f'<p class="where">{where}</p>'
        f"<p>{escape(finding.message)}</p>{evidence}"
        f"<p><b>Fix:</b> {escape(finding.remediation)}</p>{references}"
        "</article>"
    )


def _css_name(severity: Severity) -> str:
    return severity.value
