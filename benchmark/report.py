"""Turn benchmark numbers into a Markdown page."""

from typing import Any

SCENARIO_TITLES = {
    "alone": "Poisoned tool scanned alone",
    "beside_target": "Poisoned tool scanned beside the server it targets",
}
FP_TITLES = {
    "alone": "Each real server scanned alone",
    "together": "All real servers scanned together",
}


def _rate(entry: dict[str, Any]) -> str:
    return (
        f"{entry['rate']:.1%} ({entry['hits']}/{entry['total']}; "
        f"95% CI {entry['ci95_low']:.1%} to {entry['ci95_high']:.1%})"
    )


def _table(header: tuple[str, ...], rows: list[tuple[str, ...]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _split_rows(rates: dict[str, Any]) -> list[tuple[str, ...]]:
    return [
        (
            f"`{threshold}` and above",
            _rate(entry["all"]),
            _rate(entry["dev"]),
            _rate(entry["test"]),
        )
        for threshold, entry in rates.items()
    ]


def render_markdown(result: dict[str, Any]) -> str:
    suite = result["suite"]
    scanner = result["scanner"]
    detection = result["detection"]
    false_positives = result["false_positives"]
    split_header = ("Severity counted", "All", "Dev split", "Test split")
    scenarios = list(detection)

    sections = [
        f"# Benchmark results: {suite['name']}",
        f"Scanner: {scanner['name']} {scanner['version']}. "
        "This file is generated by `python -m benchmark run`; do not edit it by hand.",
        "\n".join(f"- Scanner note: {note}" for note in scanner["notes"]),
        "## Corpus",
        f"{suite['description']}. Source: {suite['source']} at revision "
        f"`{suite['revision'][:12]}`, licence {suite['licence']}.",
        f"- {suite['poisoned_tools']} poisoned tool definitions\n"
        f"- {suite['clean_tools']} real tool definitions from {suite['servers']} servers\n"
        + "\n".join(f"- Note: {note}" for note in suite["notes"]),
        "## Detection rate",
        "Share of poisoned tools on which the scanner raised a finding. Higher is better. "
        "The two scenarios differ in what the scanner is allowed to see; neither number "
        "is the whole truth without the other.",
    ]
    for scenario in scenarios:
        sections += [
            f"### {SCENARIO_TITLES.get(scenario, scenario)}",
            _table(split_header, _split_rows(detection[scenario]["rates"])),
        ]
    sections += [
        "## False-positive rate",
        "Share of real, unmodified tools on which the scanner raised a finding. Lower is better.",
    ]
    for scenario, entry in false_positives.items():
        sections += [
            f"### {FP_TITLES.get(scenario, scenario)}",
            _table(split_header, _split_rows(entry["rates"])),
        ]
    for key, title, column in (
        ("by_category", "Detection by attack goal", "Goal"),
        ("by_technique", "Detection by attack technique", "Technique"),
    ):
        names = sorted({name for scenario in scenarios for name in detection[scenario][key]})
        sections += [
            f"## {title}",
            "Counted at `medium` and above.",
            _table(
                (column, *(SCENARIO_TITLES.get(s, s) for s in scenarios)),
                [(name, *(_rate(detection[s][key][name]) for s in scenarios)) for name in names],
            ),
        ]
    rule_ids = sorted(
        {rule for s in scenarios for rule in detection[s]["labels"]}
        | {rule for entry in false_positives.values() for rule in entry["labels"]}
    )
    sections += [
        "## Which rules or threat labels did the work",
        "Counted at `medium` and above. One tool can be reported by several rules.",
        _table(
            (
                "Rule or label",
                *(f"Caught: {SCENARIO_TITLES.get(s, s).lower()}" for s in scenarios),
                *(f"Wrongly flagged: {FP_TITLES.get(s, s).lower()}" for s in false_positives),
            ),
            [
                (
                    rule,
                    *(str(detection[s]["labels"].get(rule, 0)) for s in scenarios),
                    *(str(entry["labels"].get(rule, 0)) for entry in false_positives.values()),
                )
                for rule in rule_ids
            ],
        ),
    ]
    return "\n\n".join(sections) + "\n"


def render_comparison(results: list[dict[str, Any]]) -> str:
    """One table per question, one column per scanner."""
    suite = results[0]["suite"]
    names = [f"{r['scanner']['name']} {r['scanner']['version']}" for r in results]
    thresholds = list(results[0]["detection"]["alone"]["rates"])

    def table(title: str, pick: Any) -> list[str]:
        rows = [
            (f"`{threshold}` and above", *(_rate(pick(r)[threshold]["all"]) for r in results))
            for threshold in thresholds
        ]
        return [f"### {title}", _table(("Severity counted", *names), rows)]

    sections = [
        f"# Scanner comparison: {suite['name']}",
        "This file is generated by `python -m benchmark compare`; do not edit it by hand.",
        f"Corpus: {suite['poisoned_tools']} poisoned and {suite['clean_tools']} genuine tool "
        f"definitions from {suite['servers']} servers ({suite['source']} at "
        f"`{suite['revision'][:12]}`).",
        "\n".join(
            f"- **{name}**: {note}"
            for name, result in zip(names, results, strict=True)
            for note in result["scanner"]["notes"]
        ),
        "Scanners grade severity differently. `low` and above means the scanner said "
        "anything at all about the tool; read all three rows before drawing a conclusion.",
        "## Detection rate (higher is better)",
    ]
    for scenario in results[0]["detection"]:
        sections += table(
            SCENARIO_TITLES.get(scenario, scenario),
            lambda r, scenario=scenario: r["detection"][scenario]["rates"],
        )
    sections.append("## False-positive rate (lower is better)")
    for scenario in results[0]["false_positives"]:
        sections += table(
            FP_TITLES.get(scenario, scenario),
            lambda r, scenario=scenario: r["false_positives"][scenario]["rates"],
        )
    return "\n\n".join(sections) + "\n"


def render_case_comparison(results: list[dict[str, Any]]) -> str:
    """Report for a suite of whole-server cases, one column per scanner."""
    suite = results[0]["suite"]
    names = [f"{r['scanner']['name']} {r['scanner']['version']}" for r in results]
    thresholds = list(results[0]["detection"]["rates"])

    def by_threshold(pick: Any) -> list[tuple[str, ...]]:
        return [
            (f"`{threshold}` and above", *(_rate(pick(r)[threshold]) for r in results))
            for threshold in thresholds
        ]

    medium = "medium"
    sections = [
        f"# Benchmark results: {suite['name']}",
        "This file is generated by `python -m benchmark`; do not edit it by hand.",
        f"{suite['description']}: {suite['malicious_cases']} malicious and "
        f"{suite['benign_cases']} benign tool lists.",
        _table(
            ("Source", "Licence", "Revision", "Malicious", "Benign"),
            [
                (
                    f"[{source['name']}]({source['url']})",
                    source["licence"],
                    f"`{source['revision'][:12]}`",
                    str(source["malicious_cases"]),
                    str(source["benign_cases"]),
                )
                for source in suite["sources"]
            ],
        ),
        "\n".join(f"- {note}" for note in suite["notes"]),
        "\n".join(
            f"- **{name}**: {note}"
            for name, result in zip(names, results, strict=True)
            for note in result["scanner"]["notes"]
        ),
        "## Detection rate (higher is better)",
        "Share of malicious tool lists in which the scanner flagged at least one tool.",
        _table(("Severity counted", *names), by_threshold(lambda r: r["detection"]["rates"])),
        "## False-positive rate (lower is better)",
        "Share of benign tool lists in which the scanner flagged at least one tool.",
        _table(("Severity counted", *names), by_threshold(lambda r: r["false_positives"]["rates"])),
        "## Detection by source",
        "Counted at `medium` and above.",
        _table(
            ("Source", *names),
            [
                (source, *(_rate(r["detection"]["by_source"][source][medium]) for r in results))
                for source in results[0]["detection"]["by_source"]
            ],
        ),
        "## Detection by category",
        "Counted at `medium` and above.",
        _table(
            ("Category", *names),
            [
                (
                    category,
                    *(_rate(r["detection"]["by_category"][category][medium]) for r in results),
                )
                for category in results[0]["detection"]["by_category"]
            ],
        ),
    ]
    for name, result in zip(names, results, strict=True):
        missed = result["detection"]["missed"]
        flagged = result["false_positives"]["flagged"]
        sections += [
            f"## Cases: {name}",
            "Missed at `medium` and above: "
            + (", ".join(f"`{c}`" for c in missed) or "none")
            + ".",
            "Benign lists flagged at `medium` and above: "
            + (", ".join(f"`{c}`" for c in flagged) or "none")
            + ".",
        ]
    return "\n\n".join(sections) + "\n"
